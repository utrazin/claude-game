"""Deterministic API reference generator for NoctAssetForge3D.

Reads names, signatures and docstrings from the code (the source of truth)
and writes Markdown pages under ``docs/api/``. It never executes recipes and
never modifies assets: Python surfaces are read with ``inspect`` and CLI
options are captured from each command's own ``--help`` output.

Public surfaces (explicit allowlist, nothing else is documented as stable):

- ``lib`` (``lib.__all__``): ``from lib import X``.
- ``Tools.TexturePainter`` (its ``__all__``): ``from Tools.TexturePainter import X``.
- ``Tools.recipe_context``: ``RecipePaths``, ``recipe_paths``, ``recipe_environment``.
- ``Tools.uv_builder``: ``UVBuilder``.
- CLI: ``py -3.12 -m Tools.forge <command>`` (see ``Tools.forge.COMMANDS`` plus
  ``project init`` and ``asset init|import``).

Documentation rule: every allowlisted top-level symbol must have a docstring.
Public methods without docstrings are still listed (signature only) and marked
as a documented gap; they do not fail the run.

Usage::

    py -3.12 -m Tools.api_reference            # regenerate docs/api/
    py -3.12 -m Tools.api_reference --check    # fail if docs/api/ is outdated

Exit codes: 0 up to date (or regenerated), 1 output outdated in ``--check``,
2 usage error or public symbol without documentation.
"""
from __future__ import annotations

import argparse
import importlib
import inspect
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "docs" / "api"

HEADER = ("<!-- GENERATED by `py -3.12 -m Tools.api_reference`. Do not edit by hand. -->\n"
          "<!-- Code is the source of truth; behavioral concepts live in docs/, "
          "workflow in .agents/skills/. -->\n")

RECIPE_CONTEXT_SYMBOLS = ("RecipePaths", "recipe_paths", "recipe_environment")
UV_BUILDER_SYMBOLS = ("UVBuilder",)
INK_SYMBOLS = ("Path", "line", "curve", "bezier", "arc", "vertices", "boundary", "stroke", "style", "Style")   # `from Tools.TexturePainter.ink import X`
LOOKS_SYMBOLS = ("Look", "Pass", "LayerStyle", "Overlay", "Region", "Style", "PaintLayer", "paint_looks")   # `from Tools.TexturePainter.looks import X`
