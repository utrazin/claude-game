def build_pages() -> dict[str, str]:
    lib_symbols, painter_symbols, recipe_symbols, missing = _load_python_surfaces()
    if missing:
        details = "\n".join(f"  - {name}" for name in missing)
        raise ValueError("Public API symbols without documentation:\n" + details)
    helps = {args: _capture_help(args) for args, _module in CLI_COMMANDS}
    pages = {
        "index.md": _render_index_page(),
        "lib.md": _render_module_page(
            title="lib reference (generated)",
            intro="Authoring API: `from lib import X`. Full signatures; "
                  "members without prose are marked as documented gaps.",
            symbols=lib_symbols),
        "texture-painter.md": _render_module_page(
            title="TexturePainter reference (generated)",
            intro="Painting API: `from Tools.TexturePainter import X`. "
                  "Selections, layers, decals, contact fields, export. Lineart path and stroke builders "
                  "(`ink.*`): `from Tools.TexturePainter.ink import line, curve, bezier, arc, vertices, boundary, stroke, style`; "
                  "paint them with `paint_strokes`.",
            symbols=painter_symbols),
        "recipe-context.md": _render_module_page(
            title="Recipe context and UV reference (generated)",
            intro="Saved-recipe paths (`Tools.recipe_context`) and explicit UV "
                  "sharing (`Tools.uv_builder.UVBuilder`).",
            symbols=recipe_symbols),
        "cli.md": _render_cli_page(helps),
    }
    return {name: text if text.endswith("\n") else text + "\n" for name, text in pages.items()}


def _write(pages: dict[str, str]) -> list[str]:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    written = []
    for name in sorted(pages):
        path = OUT_DIR / name
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(pages[name])
        written.append(name)
    stale = sorted(p.name for p in OUT_DIR.glob("*.md") if p.name not in pages)
    for name in stale:
        (OUT_DIR / name).unlink()
        written.append(f"{name} (removed)")
    return written


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Fail without writing when docs/api/ is outdated")
    args = parser.parse_args(argv)
    try:
        pages = build_pages()
    except ValueError as exc:
        print(f"[api_reference] FAIL {exc}", file=sys.stderr)
        return 2
    except RuntimeError as exc:
        print(f"[api_reference] FAIL {exc}", file=sys.stderr)
        return 2
    problems = []
    for name in sorted(pages):
        path = OUT_DIR / name
        if not path.is_file():
            problems.append(f"missing {name}")
        elif path.read_text(encoding="utf-8").replace("\r\n", "\n") != pages[name]:
            problems.append(f"outdated {name}")
    stale = sorted(p.name for p in OUT_DIR.glob("*.md") if p.name not in pages)
    problems.extend(f"stale {name}" for name in stale)
    if args.check:
        if problems:
            print("[api_reference] FAIL docs/api/ is outdated: " + ", ".join(problems), file=sys.stderr)
            print("[api_reference] Run `py -3.12 -m Tools.api_reference` to regenerate.", file=sys.stderr)
            return 1
        print("[api_reference] OK docs/api/ is current.")
        return 0
    for name in _write(pages):
        print(f"[api_reference] wrote docs/api/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
