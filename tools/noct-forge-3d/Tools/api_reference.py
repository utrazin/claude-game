MISSING_DOC = "_Sem docstring no código (lacuna documentada; uso operacional nas skills)._"


def _first_line(doc: str) -> str:
    for line in doc.splitlines():
        line = line.strip()
        if line:
            return line
    return ""


def _signature(obj) -> str:
    try:
        return str(inspect.signature(obj))
    except (TypeError, ValueError):
        return ""


def _public_members(obj) -> list[tuple[str, str, str, bool]]:
    """Return (name, kind, signature-or-empty, first-doc-line-or-empty) sorted by name."""
    entries = []
    for name in dir(obj):
        if name.startswith("_"):
            continue
        try:
            member = getattr(obj, name)
        except Exception:  # pragma: no cover - defensive
            continue
        try:
            static = inspect.getattr_static(obj, name)
        except Exception:  # pragma: no cover - defensive
            static = None
        if isinstance(static, property):
            entries.append((name, "property", "", _first_line(inspect.getdoc(member) or "")))
        elif callable(member):
            doc = inspect.getdoc(member) or ""
            entries.append((name, "method", _signature(member), _first_line(doc)))
    entries.sort(key=lambda item: item[0])
    return entries


def _render_symbol(name: str, obj) -> str:
    module = getattr(obj, "__module__", "?")
    sig = _signature(obj)
    doc = inspect.getdoc(obj) or ""
    if inspect.isclass(obj):
        head = f"class {name}{sig}"
    elif inspect.isfunction(obj) or inspect.isbuiltin(obj):
        head = f"def {name}{sig}"
    else:
        head = f"{name} = {sig}" if sig else name
    parts = [f"## `{name}`\n", f"Defined in `{module}`.\n", "```python\n" + head + "\n```\n"]
    parts.append(doc + "\n" if doc else MISSING_DOC + "\n")
    if inspect.isclass(obj):
        members = _public_members(obj)
        if members:
            parts.append("\n### Members\n")
            for member_name, kind, member_sig, first in members:
                if kind == "property":
                    parts.append(f"- `{member_name}` (property)"
                                 + (f" — {first}" if first else f" — {MISSING_DOC}") + "\n")
                else:
                    parts.append(f"- `{member_name}{member_sig}`"
                                 + (f" — {first}" if first else f" — {MISSING_DOC}") + "\n")
    return "\n".join(part for part in parts if part) + "\n"


def _render_module_page(*, title: str, intro: str, symbols: list[tuple[str, object]]) -> str:
    out = [HEADER + f"\n# {title}\n", intro + "\n"]
    for name, obj in symbols:
        out.append(_render_symbol(name, obj))
    return "\n".join(out)


def _collect_missing(symbols: list[tuple[str, object]]) -> list[str]:
    return sorted(name for name, obj in symbols if not inspect.getdoc(obj))


def _load_python_surfaces() -> tuple[list[tuple[str, object]], list[tuple[str, object]],
                                      list[tuple[str, object]], list[str]]:
    lib = importlib.import_module("lib")
    lib_symbols = [(name, getattr(lib, name)) for name in sorted(lib.__all__)]
    painter_mod = importlib.import_module("Tools.TexturePainter")
    painter_symbols = [(name, getattr(painter_mod, name)) for name in sorted(painter_mod.__all__)]
    ink_mod = importlib.import_module("Tools.TexturePainter.ink")
    painter_symbols += [("ink." + name, getattr(ink_mod, name)) for name in INK_SYMBOLS]
    for module_name, names in (("looks", LOOKS_SYMBOLS), ("theme", THEME_SYMBOLS)):
        module = importlib.import_module("Tools.TexturePainter." + module_name)
        painter_symbols += [(module_name + "." + name, getattr(module, name)) for name in names]
    context_mod = importlib.import_module("Tools.recipe_context")
    uv_mod = importlib.import_module("Tools.uv_builder")
    recipe_symbols = [("Tools.recipe_context." + name, getattr(context_mod, name))
                      for name in RECIPE_CONTEXT_SYMBOLS]
    recipe_symbols += [("Tools.uv_builder." + name, getattr(uv_mod, name))
                       for name in UV_BUILDER_SYMBOLS]
    missing = (_collect_missing([("lib." + n, o) for n, o in lib_symbols])
               + _collect_missing([("Tools.TexturePainter." + n, o) for n, o in painter_symbols])
               + _collect_missing(recipe_symbols))
    return lib_symbols, painter_symbols, recipe_symbols, missing


def _capture_help(forge_args: tuple[str, ...]) -> str:
    proc = subprocess.run(
        [sys.executable, "-m", "Tools.forge", *forge_args, "--help"],
        cwd=ROOT, capture_output=True, text=True, timeout=120,
    )
    text = (proc.stdout or "") + (proc.stderr or "")
    if proc.returncode != 0 or "usage:" not in text:
        raise RuntimeError(f"Could not capture help for `forge {' '.join(forge_args)}` "
                           f"(exit {proc.returncode}): {text[:500]}")
    lines = [line.rstrip() for line in text.strip().splitlines()]
    cleaned = "\n".join(lines).replace(str(ROOT), "<repo>")
    return cleaned + "\n"


def _render_cli_page(helps: dict[tuple[str, ...], str]) -> str:
    out = [HEADER + "\n# CLI reference (generated)\n",
           "Canonical invocation: `py -3.12 -m Tools.forge <command>`. "
           "Options below are captured from each command's own `--help`; "
           "project/asset selection uses `PROJECT --asset ID`.\n"]
    for forge_args, _module in CLI_COMMANDS:
        label = " ".join(forge_args)
        module = dict(CLI_COMMANDS)[forge_args]
        out.append(f"## `forge {label}`\n")
        out.append(f"Backing module: `Tools.{module.split('.', 1)[1]}`.\n")
        out.append("```text\n" + helps[forge_args].rstrip() + "\n```\n")
    return "\n".join(out)


