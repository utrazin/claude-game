import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import vm from 'node:vm';
const context = vm.createContext({ AbortController, setTimeout, clearTimeout });
vm.runInContext(readFileSync('viewer/forge-session.js', 'utf8'), context);
const session = context.ForgeSession;
const requests = new session.LatestRequest();
const first = requests.begin(), second = requests.begin();
assert.equal(first.current(), false); assert.equal(first.signal.aborted, true); assert.equal(second.current(), true);
let concurrent = 0, peak = 0, calls = 0, release: () => void = () => {};
const poller = new session.Poller(async () => { concurrent++; peak = Math.max(peak, concurrent); calls++; await new Promise<void>(resolve => { release = resolve; }); concurrent--; }, 10000);
const work = poller.refresh(); await poller.refresh(); await poller.refresh();
release(); await work;
await new Promise(resolve => setTimeout(resolve, 20));
assert.equal(calls, 2); assert.equal(peak, 1); poller.stop(); release();
const manifest = JSON.parse(readFileSync('viewer/runtime-version.json', 'utf8'));
for (const [file, hash] of Object.entries(manifest.hashes)) assert.equal(createHash('sha256').update(readFileSync('viewer/' + file)).digest('hex'), hash);
console.log('Session: latest intent, cancellation, coalescing and runtime manifest passed.');
